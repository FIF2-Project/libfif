"""Accumulates per-run context statistics and emits the default table."""
import sys, os

def read_run(path):
    with open(path) as f:
        n, count = f.readline().split()
        vals = [int(f.readline()) for _ in range(int(n))]
    return int(n), int(count), vals

if sys.argv[1] == '--emit':
    acc, out = sys.argv[2], sys.argv[3]
    n, count, vals = read_run(acc)
    probs = []
    for v in vals:
        p = int(round(v / count))
        probs.append(min(2047, max(1, p)))      # keep every context codeable
    with open(out, 'w') as f:
        f.write('/* ------------------------------------------------------------------------\n')
        f.write(' * libfif v3.5 / fif v2.5 - FIF2 fractal image format\n')
        f.write(' *\n')
        f.write(' * libfif and fif:  Oskar Behzadpour\n')
        f.write(' * FIF2 format:     Rezar Behzad\n')
        f.write(' * Web:             www.FractalImageCompression.com\n')
        f.write(' * Contact:         oskar@fractalimagecompression.com\n')
        f.write(' *\n')
        f.write(' * Copyright (c) 2026 Oskar Behzadpour\n')
        f.write(' * ---------------------------------------------------------------------- */\n')
        f.write('\n')
        f.write('/* Generated by tools/train_contexts.sh - do not edit by hand.\n'
                ' * Adapted probabilities averaged over the training set, so a tile\n'
                ' * starts where a typical tile ends instead of at one half. */\n')
        f.write('static const uint16_t kDefaultProbs[%d] = {\n' % n)
        for i in range(0, n, 16):
            f.write('    ' + ','.join(str(x) for x in probs[i:i+16]) + ',\n')
        f.write('};\n')
    sys.exit(0)

run, acc = sys.argv[1], sys.argv[2]
n, count, vals = read_run(run)
if os.path.exists(acc):
    n2, c2, v2 = read_run(acc)
    assert n2 == n, 'context layout changed mid-training'
    count += c2
    vals = [a + b for a, b in zip(vals, v2)]
with open(acc, 'w') as f:
    f.write('%d %d\n' % (n, count))
    for v in vals:
        f.write('%d\n' % v)
